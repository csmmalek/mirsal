function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** يختار 5 أسئلة من كل مستوى ويرتبها تصاعدياً في الصعوبة، مع خلط ترتيب الخيارات. */
export function buildRound(perLevel = 5): Question[] {
  const round: Question[] = [];
  for (const d of [1, 2, 3] as const) {
    round.push(...shuffle(QUESTIONS.filter((q) => q.difficulty === d)).slice(0, perLevel));
  }
  return round.map((q) => {
    // الأسئلة التي تشير خياراتها إلى رسم (أ/ب/ج) تبقى بترتيبها لتطابق الرسم.
    if (q.diagram === 'string-cut' || q.diagram === 'bottle') return q;
    const order = shuffle(q.options.map((_, i) => i));
    return { ...q, options: order.map((i) => q.options[i]), answer: order.indexOf(q.answer) };
  });
}

